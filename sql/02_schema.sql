-- Esquema relacional del asistente RAG multiempresa.
-- Ejecutar con psql, conectado a rag_chatbot. ON_ERROR_STOP impide continuar
-- si la guarda rechaza otra base.
-- Requiere la extensión vector, creada previamente en 01_extensions.sql.
-- No inserta datos ni define usuarios, roles o políticas RLS.
-- Puede ejecutarse más de una vez: las tablas y el índice ya existentes se conservan.

\set ON_ERROR_STOP on

-- Aborta antes de abrir la transacción y de crear tablas o índices
-- si la base activa no es rag_chatbot.
DO $$
BEGIN
    IF current_database() = 'rag_multitenant' THEN
        RAISE EXCEPTION
            'Rechazado: rag_multitenant pertenece a la infraestructura anterior. Este script solo puede ejecutarse en rag_chatbot.';
    END IF;

    IF current_database() <> 'rag_chatbot' THEN
        RAISE EXCEPTION
            'Ejecute este script en rag_chatbot, no en %',
            current_database();
    END IF;
END
$$;

BEGIN;

-- Catálogo de empresas cliente. El nombre es único para evitar duplicados lógicos.
-- GENERATED BY DEFAULT AS IDENTITY permite asignar el id explícitamente en pruebas
-- y, si no se indica, lo genera PostgreSQL.
CREATE TABLE IF NOT EXISTS empresas (
    id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nombre TEXT NOT NULL UNIQUE,
    created_at TIMESTAMPTZ NOT NULL DEFAULT NOW()
);

-- Fragmentos recuperables de cada empresa.
-- empresa_id vincula cada fragmento a una sola empresa.
-- ON DELETE RESTRICT impide borrar una empresa mientras conserve fragmentos,
-- evitando una eliminación accidental en cascada.
-- VECTOR(384) fija la dimensión del modelo paraphrase-multilingual-MiniLM-L12-v2.
-- No se crea un índice HNSW ni IVFFlat: con pocos documentos la búsqueda exacta
-- es suficiente y evita el coste de un índice aproximado.
CREATE TABLE IF NOT EXISTS fragmentos (
    id BIGSERIAL PRIMARY KEY,
    empresa_id INTEGER NOT NULL,
    documento TEXT NOT NULL,
    texto TEXT NOT NULL,
    embedding VECTOR(384) NOT NULL,
    created_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    CONSTRAINT fragmentos_empresa_id_fkey
        FOREIGN KEY (empresa_id)
        REFERENCES empresas (id)
        ON DELETE RESTRICT
        ON UPDATE RESTRICT
);

-- Acelera los filtros y uniones por empresa, y la comprobación de la clave foránea.
-- PostgreSQL no crea automáticamente un índice sobre la columna que referencia.
CREATE INDEX IF NOT EXISTS fragmentos_empresa_id_idx
    ON fragmentos (empresa_id);

COMMIT;
